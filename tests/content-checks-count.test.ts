import assert from "node:assert/strict";
import { describe, it } from "node:test";
import { countText } from "../src/content/count-text.ts";

// 期望值都是手算的字面值，不由實作推導。
describe("countText", () => {
  const cases: [string, string, number][] = [
    ["空字串", "", 0],
    ["純中文每字計 1", "你好世界", 4],
    ["中英混排：英文詞計 1", "Hello 世界", 3],
    ["小數點在數字內部不拆開", "3.5 公分", 3],
    ["連字號在詞內部不拆開", "X-ray 檢查", 3],
    ["撇號在詞內部不拆開", "don't stop", 2],
    ["詞尾的句點不屬於詞", "end. 好", 2],
    ["連續兩個連字號會拆成兩個詞", "a--b", 2],
    ["數字與漢字混排", "2026年1月15日", 6],
    ["全形標點不計", "「你好，世界！」", 4],
    ["空白與換行不計", "你 好\n\n世　界", 4],
    ["Markdown 語法符號不計", "## 標題\n\n- **粗體** _斜體_", 6],
    ["假名各計 1", "ひらがなカタカナ", 8],
    ["注音符號各計 1", "ㄅㄆㄇ", 3],
    ["圖片語法整段不計", "前![圖片說明 alt](./a.webp)後", 2],
    ["圖片 alt 內的英文也不計", "![A photo](./a.webp)", 0],
    ["連結只計文字", "請看[維基百科](https://example.com/a-b)了解", 8],
    ["連結文字內的英文詞計 1", "[X-ray](https://x.example/y)", 1],
    ["圖片與連結並存", "圖![說明](./a.webp)見[官網](https://e.example)結束", 6],
    ["千分位數字計 1", "3,000 字", 2],
    ["多組千分位仍計 1", "共 100,000 人", 3],
    ["千分位帶小數仍計 1", "3,000,000.5", 1],
    ["逗號後不足三位數不是千分位", "1,23", 2],
    ["逗號後多於三位數不是千分位", "1,2345", 2],
    ["字母後的逗號不是千分位", "a,123", 2],
    ["諺文每個音節計 1", "한국어", 3],
    ["諺文與英文混排", "한국 KOREA", 3],
    ["希臘字母連續成詞計 1", "αβγ δ", 2],
    ["西里爾字母連續成詞計 1", "Привет мир", 2],
    ["長音符號計 1", "ひらがなー", 5],
    ["HTML 註解不計", "前<!-- 隱藏 hidden -->後", 2],
    ["多行 HTML 註解不計", "前<!--\n隱藏\n-->後", 2],
    ["參考式連結定義整行不計", '[ref]: https://a.example "標題文字"\n文', 1],
    ["腳註定義是正文，照計（編號 1 與兩字）", "[^1]: 注釋", 3],
    ["裸網址不計", "見https://example.com/a-b?x=1完", 2],
    ["尖括號網址不計", "見<https://example.com>完", 2],
    ["連結網址內的英數不計", "[好](https://a1.example/b2/c3)", 1],
  ];
  for (const [name, input, expected] of cases) {
    it(name, () => assert.equal(countText(input), expected));
  }
});
